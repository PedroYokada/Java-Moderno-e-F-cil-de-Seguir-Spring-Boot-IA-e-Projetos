
public class promocoes {

    public static void main(String[] args) {
        byte a = 10;
        int b = a + 5;
        System.out.println("Resultado de b: " + b);

        int c = 10;
        long d = 15L;
        long e = c + d;
        System.out.println("Resultado de e: " + e);

        int f = 10;
        float g = 1.5f;
        float h = f + g;
        System.out.println("Resultado de h: " + h);
    }
}
