
public class atribuicao2 {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        int c = 30;
        int d = 40;
        int e = 50;

        a += 5;
        b -= 5;
        c *= 2;
        d /= 2;
        e %= 2;

        System.out.println("Valor de A com incremento = " + a);
        System.out.println("Valor de B com incremento = " + b);
        System.out.println("Valor de C com incremento = " + c);
        System.out.println("Valor de D com incremento = " + d);
        System.out.println("Valor de E com incremento = " + e);
    }
}
