package operadores;

public class atribuicao {
  public static void main(String[] args) {
    double a = 1000.10;
    double b = 1000.20;

    System.out.println(a + " = " + b + " ,a condição é: " + (a == b));
    System.out.println(a + " != " + b + " ,a condição é: " + (a != b));
    System.out.println(a + " > " + b + " ,a condição é: " + (a > b));
    System.out.println(a + " < " + b + " ,a condição é: " + (a < b));
    System.out.println(a + " >= " + b + " ,a condição é: " + (a >= b));
    System.out.println(a + " <= " + b + " ,a condição é: " + (a <= b));
  }
}
