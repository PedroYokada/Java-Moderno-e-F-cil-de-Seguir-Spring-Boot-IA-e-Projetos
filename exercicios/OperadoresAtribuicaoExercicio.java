
public class OperadoresAtribuicaoExercicio {

    public static void main(String[] args) {
        int numero = 5;

        System.out.println("NUMERO ANTES DA ATRIBUIÇÃO DE SOMA = " + numero);
        numero += 3;
        System.out.println("NUMERO DEPOIS DO ATRIBUIÇÃO DE SOMA +3 = " + numero);

        System.out.println("NUMERO ANTES DA ATRIBUIÇÃO DE SUBTRAÇÃO = " + numero);
        numero -= 2;
        System.out.println("NUMERO DEPOIS DA ARIBUIÇÃO DE SUBTRAÇÃO -2 = " + numero);

        System.out.println("NUMERO ANTES DA ATRIBUIÇÃO DE MULTIPLICAÇÃO = " + numero);
        numero *= 4;
        System.out.println("NUMERO DEPOIS DA ATRIBUIÇÃO DE MULTIPLICAÇÃO POR 4 = " + numero);

        System.out.println("NUMERO ANTES DA ATRIBUIÇÃO DE DIVISÃO = " + numero);
        numero /= 2;
        System.out.println("NUMERO DEPOIS DA ATRIBUIÇÃO DE DIVISÃO POR 2 = " + numero);

        

    }
}
