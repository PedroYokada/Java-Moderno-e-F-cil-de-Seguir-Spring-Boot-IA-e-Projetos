
public class IncrementoDecremento {

    public static void main(String[] args) {
        int contador = 10;

        System.out.println("CONTADOR ANTES DO INCREMENTO = " + contador);
        contador++;
        System.out.println("CONTADOR DEPOIS DO INCREMENTO = " + contador);

        
        System.out.println("CONTADOR ANTES DO DECREMENTO = " + contador);
        contador--;
        System.out.println("CONTADOR DEPOIS DO DECREMENTO = " + contador);

    }
}
